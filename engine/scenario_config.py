"""
Scenarios (أنواع السيناريوهات): several named test flows for the same screen.

  config/scenarios/<screen>__<scenario>.json      e.g. cash_receipt__customer_to_customer.json
  tests/scenarios/test_scn_<screen>__<scenario>.py (generated)

A scenario has the same shape as a screen config (fields, strategies, before-save
buttons, checks) plus:  screen_key, scenario_key, scenario_name.
"""
import json
import re
from datetime import datetime
from pathlib import Path

from engine import screen_config as sc

BASE_DIR = sc.BASE_DIR
from config import paths  # noqa: E402
from config.storage import save_json, load_json, to_trash  # noqa: E402
SCENARIOS_DIR = paths.SCENARIOS_DIR
TESTS_DIR = BASE_DIR / "tests" / "scenarios"

PART_RE = re.compile(r"^[a-z][a-z0-9_]{0,40}$")
SEP = "__"


class ScenarioError(sc.ConfigError):
    pass


def full_key(screen_key: str, scenario_key: str) -> str:
    return f"{screen_key}{SEP}{scenario_key}"


def test_path_for(screen_key: str, scenario_key: str) -> str:
    return f"tests/scenarios/test_scn_{full_key(screen_key, scenario_key)}.py::test_scenario_flow"


def stub_path(screen_key, scenario_key) -> Path:
    return TESTS_DIR / f"test_scn_{full_key(screen_key, scenario_key)}.py"


def normalize(cfg: dict) -> dict:
    screen_key = str(cfg.get("screen_key") or "").strip().lower()
    scenario_key = str(cfg.get("scenario_key") or "").strip().lower()
    scenario_name = str(cfg.get("scenario_name") or "").strip()
    if not PART_RE.match(screen_key) or SEP in screen_key:
        raise ScenarioError("اختاري الشاشة الأول (مفتاح الشاشة بالإنجليزي، زي cash_receipt)")
    if not PART_RE.match(scenario_key) or SEP in scenario_key:
        raise ScenarioError("مفتاح السيناريو لازم يبدأ بحرف إنجليزي صغير وفيه حروف/أرقام/_ بس، مثال: customer_to_customer")
    if not scenario_name:
        raise ScenarioError("اكتبي اسم السيناريو، مثال: سند قبض من عميل إلى عميل")
    base = dict(cfg)
    base["key"] = full_key(screen_key, scenario_key)
    out = sc.normalize(base)
    out["screen_key"] = screen_key
    out["scenario_key"] = scenario_key
    out["scenario_name"] = scenario_name
    out["screen_name"] = str(cfg.get("screen_name") or cfg.get("name_ar") or screen_key)
    # the name shown everywhere: "سند القبض — من عميل إلى عميل"
    out["name_ar"] = f"{out['screen_name']} — {scenario_name}"
    out["name_en"] = str(cfg.get("name_en") or out["name_ar"])
    out["icon"] = str(cfg.get("icon") or "🎬")
    return out


def _path(screen_key, scenario_key) -> Path:
    return SCENARIOS_DIR / f"{full_key(screen_key, scenario_key)}.json"


def load(screen_key: str, scenario_key: str) -> dict:
    p = _path(screen_key, scenario_key)
    if not p.exists():
        raise ScenarioError(f"مفيش سيناريو '{scenario_key}' للشاشة '{screen_key}'")
    return normalize(load_json(p, {}))


def load_by_full_key(key: str) -> dict:
    if SEP not in key:
        raise ScenarioError(f"مفتاح سيناريو غلط: {key}")
    screen_key, scenario_key = key.split(SEP, 1)
    return load(screen_key, scenario_key)


def list_all(screen_key: str = None) -> list:
    out = []
    if not SCENARIOS_DIR.exists():
        return out
    for p in sorted(SCENARIOS_DIR.glob("*.json")):
        try:
            c = normalize(load_json(p, {}))
        except Exception as e:
            sk = p.stem.split(SEP, 1)
            c = {"key": p.stem, "screen_key": sk[0], "scenario_key": sk[-1], "scenario_name": p.stem,
                 "name_ar": p.stem, "error": str(e)[:300]}
        if screen_key and c.get("screen_key") != screen_key:
            continue
        out.append(c)
    return out


STUB_TEMPLATE = '''"""
Auto-generated by the Screen Builder for the scenario: {name}
Config: config/scenarios/{key}.json  -- edit the scenario, not this file.
"""
import allure
import pytest

from engine.screen_runner import run_scenario_test


@allure.feature("Scenarios")
@allure.story("{name}")
@pytest.mark.screen
def test_scenario_flow(driver, credentials):
    run_scenario_test(driver, credentials, "{screen}", "{scenario}")
'''


def write_stub(cfg: dict) -> Path:
    TESTS_DIR.mkdir(parents=True, exist_ok=True)
    init = TESTS_DIR / "__init__.py"
    if not init.exists():
        init.write_text("", encoding="utf-8")
    name = cfg["name_ar"].replace('"', "'").replace("\\", "/")
    p = stub_path(cfg["screen_key"], cfg["scenario_key"])
    p.write_text(STUB_TEMPLATE.format(key=cfg["key"], name=name, screen=cfg["screen_key"],
                                      scenario=cfg["scenario_key"]), encoding="utf-8")
    return p


def save(cfg: dict) -> dict:
    cfg = normalize(cfg)
    cfg["updated_at"] = datetime.now().isoformat(timespec="seconds")
    save_json(_path(cfg["screen_key"], cfg["scenario_key"]), cfg)
    write_stub(cfg)
    return cfg


def delete(screen_key: str, scenario_key: str) -> bool:
    found = to_trash(_path(screen_key, scenario_key))
    st = stub_path(screen_key, scenario_key)
    if st.exists():
        st.unlink()
        found = True
    return found


def sync_stubs() -> int:
    n = 0
    for c in list_all():
        if not c.get("error") and not stub_path(c["screen_key"], c["scenario_key"]).exists():
            write_stub(c)
            n += 1
    return n
